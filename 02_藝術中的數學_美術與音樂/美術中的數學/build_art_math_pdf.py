print("=== Step 2: Extracting & Assembling Pristine HTML ===")
with open(input_source_py, 'r', encoding='utf-8', errors='ignore') as f:
    lines = f.readlines()

raw_html_lines = []
first_line = lines[23]
idx = first_line.find('<!DOCTYPE')
raw_html_lines.append(first_line[idx:])

for l in lines[24:1132]:
    raw_html_lines.append(l)

last_line = lines[1132]
if "'''" in last_line:
    idx2 = last_line.find("'''")
    if idx2 > 0:
        raw_html_lines.append(last_line[:idx2])
else:
    raw_html_lines.append(last_line)

content = "".join(raw_html_lines)

# Fix CSS double braces
def fix_css(match):
    s = match.group(0)
    return s.replace('{{', '{').replace('}}', '}')

content = re.sub(r'<style>.*?</style>', fix_css, content, flags=re.DOTALL)

# Fix Script double braces
def fix_script(match):
    s = match.group(0)
    return s.replace('{{', '{').replace('}}', '}')

content = re.sub(r'<script>.*?</script>', fix_script, content, flags=re.DOTALL)

# Replace Brand Asset Tokens
content = content.replace('{logo_data_uri}', logo_data_uri)
content = content.replace('{svg_data_uri}', svg_data_uri)
content = content.replace('{logo_base64}', logo_base64)
content = content.replace('{svg_base64}', svg_base64)

# Fix inline page-break style if needed
content = content.replace('{{ page-break-before: always; break-before: page; }}', '{ page-break-before: always; break-before: page; }')

# Clean trailing artifact quotes
content = content.strip()
if content.endswith("'''"):
    content = content[:-3].strip()

with open(output_html, 'w', encoding='utf-8') as f:
    f.write(content)

print(f"Pristine HTML written: {output_html} ({len(content)} chars)")

print("=== Step 3: Compiling PDF via Headless Chrome ===")
chrome_path = r'C:\Program Files\Google\Chrome\Application\chrome.exe'
