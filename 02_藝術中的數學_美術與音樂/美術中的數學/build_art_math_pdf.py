cmd = [
    chrome_path,
    '--headless',
    '--disable-gpu',
    '--virtual-time-budget=8000',
    '--no-pdf-header-footer',
    f'--print-to-pdf={output_pdf}',
    file_uri
]

print(f"Executing: {' '.join(cmd)}")
